/**
 * ArtifactMakeCommand
 *
 * Scaffolds a complete modular Artifact directory structure inside `artifacts/{name}/`.
 *
 * Generated structure:
 *   artifacts/{name}/
 *   ├── art.php                              — Artifact manifest (id, name, version, providers, capabilities)
 *   ├── composer.json                        — Package definition (ugarit-artifacts/{name})
 *   ├── database/
 *   │   ├── factories/
 *   │   ├── migrations/
 *   │   └── seeders/
 *   └── src/
 *       ├── Providers/{Name}ServiceProvider.php
 *       ├── Models/
 *       ├── Contracts/Repositories/            — Repository contracts, bound by convention
 *       ├── Repositories/
 *       ├── Policies/
 *       ├── Enums/                             — Results of the capabilities and features
 *       ├── Parcels/
 *       ├── Outcomes/
 *       ├── Capabilities/
 *       ├── Features/
 *       ├── Http/Controllers/
 *       ├── Http/Requests/
 *       ├── Http/Resources/
 *       └── Rules/
 *
 * Unless --minimal, the artifact summary is generated by make:summary: Capabilities/Artifact/
 * ShowArtifactCapability, its result, Http/Controllers/Artifact/ArtifactController and the
 * `{name}.artifact.show` route in routes/web.php. With --panel (or when confirmed), make:panel
 * creates its panel on the frontend, the summary page included.
 */
#[AsCommand(name: 'make:artifact')]
class ArtifactMakeCommand extends Command
{
