<?php

declare(strict_types=1);

namespace Heritage\Foundation\Console;

use Heritage\Console\Command;
use Heritage\Filesystem\Filesystem;
use Heritage\Support\Str;
use Symfony\Component\Console\Attribute\AsCommand;

/**
 * Generates the backend of an artifact's summary: ShowArtifactCapability, which returns the
 * artifact's ArtifactSummary (manifest, totals, entities, latest activity), its result enum, the
 * ArtifactController rendering `{artifact}::artifact/Show`, and the `{artifact}.artifact.show` route,
 * which takes the place of a former `{artifact}.module.show` route.
 *
 * Its page is generated by make:panel (or make:summary-page) on the frontend.
 */
#[AsCommand(name: 'make:summary')]
class SummaryMakeCommand extends Command
{
    /**
     * The name and signature of the console command.
     *
     * @var string
     */
    protected $signature = 'make:summary
                    {artifact : The artifact summarized (e.g. library)}
                    {--f|force : Overwrite the classes that already exist}';

    /**
     * The console command description.
     *
     * @var string
     */
    protected $description = 'Create the summary capability of an artifact, its controller and its {artifact}.artifact.show route';

    /**
     * Create a new command instance.
     *
     * @param  Filesystem  $files
     */
    public function __construct(protected Filesystem $files)
    {
        parent::__construct();
    }

    /**
     * Execute the console command.
     *
     * @return int
     */
    public function handle(): int
    {
        $artifact = strtolower(trim((string) $this->argument('artifact')));
        $base = $this->ugarit->basePath("artifacts/{$artifact}");

        if (! $this->files->isDirectory($base)) {
            $this->components->error("The artifact [{$artifact}] does not exist; create it with make:artifact.");

            return self::FAILURE;
        }

        $namespace = $this->artifactNamespace($artifact);
        $replace = [
            '{{ namespace }}' => $namespace,
            '{{ artifact }}' => $artifact,
            '{{ title }}' => Str::headline($artifact),
        ];

        $this->call('make:result', array_filter([
            'name' => 'Artifact/Capabilities/ShowArtifactResult',
            '--artifact' => $artifact,
            '--feedback' => 'showed',
            '--force' => (bool) $this->option('force'),
        ]));

        $this->writeClass("{$base}/src/Capabilities/Artifact/ShowArtifactCapability.php", 'capability', $replace);
        $this->writeClass("{$base}/src/Http/Controllers/Artifact/ArtifactController.php", 'controller', $replace);
        $this->registerRoute($artifact, "{$namespace}\\Http\\Controllers\\Artifact\\ArtifactController");

        return self::SUCCESS;
    }

    /**
     * Write a class from a summary stub, unless it exists and --force is not given.
     *
     * @param  string  $path
     * @param  string  $stub  The stub name under stubs/summary.
     * @param  array<string, string>  $replace
     * @return void
     */
    protected function writeClass(string $path, string $stub, array $replace): void
    {
        if ($this->files->exists($path) && ! $this->option('force')) {
            $this->components->info(sprintf('%s [%s] already exists.', basename($path, '.php'), $path));

            return;
        }

        $this->files->ensureDirectoryExists(dirname($path));
        $this->files->put($path, str_replace(array_keys($replace), array_values($replace), $this->files->get($this->stubPath($stub))));
        $this->components->info(sprintf('%s [%s] created successfully.', basename($path, '.php'), $path));
    }

    /**
     * The path of a summary stub; the application's stubs/summary folder overrides the framework's.
     *
     * @param  string  $stub
     * @return string
     */
    protected function stubPath(string $stub): string
    {
        $custom = $this->ugarit->basePath("stubs/summary/{$stub}.stub");

        return $this->files->exists($custom) ? $custom : __DIR__."/stubs/summary/{$stub}.stub";
    }

    /**
     * Register the summary route: in place of a former `{artifact}.module.show` route in any of the
     * artifact's route files, else in its routes/web.php in place of a Route::inertia() summary
     * route, else first in its group, else in a new file grouping the artifact's routes under
     * panel/artifact/{artifact}.
     *
     * @param  string  $artifact
     * @param  string  $controller
     * @return void
     */
    protected function registerRoute(string $artifact, string $controller): void
    {
        $path = $this->ugarit->basePath("artifacts/{$artifact}/routes/web.php");
        $route = "Route::get('/', [ArtifactController::class, 'show'])->name('{$artifact}.artifact.show');";
        $import = "use {$controller};";
        $files = $this->files->glob($this->ugarit->basePath("artifacts/{$artifact}/routes/*.php")) ?: [];

        foreach ($files as $file) {
            if (str_contains($this->files->get($file), "[ArtifactController::class, 'show']")) {
                $this->components->info("Routes [{$file}] already register [{$artifact}.artifact.show].");

                return;
            }
        }

        foreach ($files as $file) {
            $content = $this->files->get($file);
            $migrated = $this->replaceModuleRoute($content, $artifact, $route);

            if ($migrated !== null) {
                $eol = str_contains($content, "\r\n") ? "\r\n" : "\n";
                $this->files->put($file, $this->addImport($migrated, $import, $eol));
                $this->components->info("Routes [{$file}] register [{$route}] in place of [{$artifact}.module.show].");

                return;
            }
        }

        if (! $this->files->exists($path)) {
            $this->files->ensureDirectoryExists(dirname($path));
            $this->files->put($path, "<?php\n\nuse Heritage\\Support\\Facades\\Route;\n{$import}\n\nRoute::middleware(['web', 'auth'])->prefix('panel/artifact/{$artifact}')->group(function () {\n    {$route}\n});\n");
            $this->components->info("Routes [{$path}] created with [{$route}].");

            return;
        }

        $content = $this->files->get($path);
        $eol = str_contains($content, "\r\n") ? "\r\n" : "\n";
        $inertia = '/^([ \t]*)Route::inertia\([^;]*->name\(\''.preg_quote("{$artifact}.artifact.show", '/').'\'\);[ \t]*$/m';

        if (preg_match($inertia, $content)) {
            $content = preg_replace($inertia, '$1'.$route, $content, 1);
        } elseif (preg_match('/->group\(function \(\) \{\r?\n/', $content, $match, PREG_OFFSET_CAPTURE)) {
            $content = substr_replace($content, "    {$route}{$eol}{$eol}", $match[0][1] + strlen($match[0][0]), 0);
        } else {
            $content = rtrim($content).$eol.$eol.$route.$eol;
        }

        $this->files->put($path, $this->addImport($content, $import, $eol));
        $this->components->info("Routes [{$path}] register [{$route}].");
    }

    /**
     * Replace a former `{artifact}.module.show` route with the summary route; a controller group
     * left holding only the summary route is unwrapped, and the ModuleController import dropped
     * once nothing refers to it.
     *
     * @param  string  $content
     * @param  string  $artifact
     * @param  string  $route
     * @return string|null  The new content, or null when the file has no such route.
     */
    protected function replaceModuleRoute(string $content, string $artifact, string $route): ?string
    {
        $former = '/^([ \t]*)Route::(?:get|inertia)\([^;]*->name\(\''.preg_quote("{$artifact}.module.show", '/').'\'\);[ \t]*$/m';

        if (! preg_match($former, $content)) {
            return null;
        }

        $content = preg_replace($former, '$1'.$route, $content, 1);
        $content = preg_replace(
            '/^([ \t]*)Route::controller\(ModuleController::class\)->group\(function \(\) \{\s*('.preg_quote($route, '/').')\s*\}\);/m',
            '$1$2',
            $content
        );

        if (! preg_match('/(?<![\\\\\w])ModuleController::class/', $content)) {
            $content = preg_replace('/^use [^;\s]*\\\\ModuleController;[ \t]*\r?\n/m', '', $content);
        }

        return $content;
    }

    /**
     * Add a "use" statement after the last one of a PHP file, unless it is there.
     *
     * @param  string  $content
     * @param  string  $import
     * @param  string  $eol
     * @return string
     */
    protected function addImport(string $content, string $import, string $eol): string
    {
        if (str_contains($content, $import)) {
            return $content;
        }

        if (preg_match_all('/^use [^;]+;/m', $content, $uses, PREG_OFFSET_CAPTURE)) {
            [$last, $offset] = end($uses[0]);

            return substr_replace($content, $eol.$import, $offset + strlen($last), 0);
        }

        return (string) preg_replace('/^<\?php\r?\n/', '<?php'.$eol.$eol.$import.$eol, $content, 1);
    }

    /**
     * The root namespace of an artifact: its manifest's, else Ugarit\Artifacts\{Studly}.
     *
     * @param  string  $artifact
     * @return string
     */
    protected function artifactNamespace(string $artifact): string
    {
        $manifest = $this->ugarit->basePath("artifacts/{$artifact}/art.php");

        if ($this->files->exists($manifest) && preg_match('/^namespace\s+([^;]+);/m', $this->files->get($manifest), $match)) {
            return trim($match[1], '\\ ');
        }

        return 'Ugarit\\Artifacts\\'.Str::studly($artifact);
    }
}
